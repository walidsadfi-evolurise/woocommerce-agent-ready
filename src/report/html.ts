import type { AuditReport } from "../types.js";

function esc(s: string): string {
  return s.replace(/[&<>"']/g, (ch) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[ch] ?? ch);
}

/** Self-contained HTML report: no external assets, prints well, dark-mode aware. */
export function renderHtml(report: AuditReport): string {
  const pct = Math.round((report.score / report.max) * 100);
  const tone = pct >= 70 ? "good" : pct >= 40 ? "mid" : "bad";

  const checks = report.checks
    .map((ch) => {
      const findings = ch.findings
        .map(
          (f) => `<li class="f-${f.severity}"><span>${esc(f.message)}</span>${
            f.fix ? `<div class="fix"><strong>Fix:</strong> ${esc(f.fix)}</div>` : ""
          }</li>`,
        )
        .join("");
      return `<section class="check s-${ch.status}">
  <header><span class="badge">${ch.status.toUpperCase()}</span><h2>${esc(ch.title)}</h2><span class="pts">${ch.score}/${ch.max}</span></header>
  <p class="why">${esc(ch.why)}</p>
  <ul>${findings}</ul>
</section>`;
    })
    .join("\n");

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Agent-readiness audit: ${esc(report.baseUrl)}</title>
<style>
:root{--bg:#fff;--fg:#111;--muted:#666;--line:#e5e5e5;--good:#1d9e75;--mid:#ba7517;--bad:#a32d2d;--fix:#f4f7f6}
@media(prefers-color-scheme:dark){:root{--bg:#0b1220;--fg:#eee;--muted:#9aa;--line:#233;--fix:#121c2c}}
body{margin:0;font:16px/1.6 system-ui,-apple-system,Segoe UI,Roboto,sans-serif;background:var(--bg);color:var(--fg)}
main{max-width:860px;margin:0 auto;padding:32px 20px}
h1{font-size:22px;margin:0 0 4px}.url{color:var(--muted);word-break:break-all}
.score{display:flex;align-items:baseline;gap:16px;margin:24px 0;padding:20px;border:1px solid var(--line);border-radius:12px}
.score .n{font-size:48px;font-weight:600}.score.good .n{color:var(--good)}.score.mid .n{color:var(--mid)}.score.bad .n{color:var(--bad)}
.check{border:1px solid var(--line);border-radius:12px;padding:16px 20px;margin:12px 0}
.check header{display:flex;align-items:center;gap:12px}.check h2{font-size:17px;margin:0;flex:1}
.badge{font-size:12px;font-weight:600;padding:2px 8px;border-radius:6px;border:1px solid var(--line)}
.s-pass .badge{color:var(--good)}.s-warn .badge{color:var(--mid)}.s-fail .badge{color:var(--bad)}.s-skip .badge{color:var(--muted)}
.pts{color:var(--muted)}.why{color:var(--muted);margin:6px 0 10px;font-size:14px}
ul{list-style:none;padding:0;margin:0}li{padding:6px 0;border-top:1px solid var(--line)}
.f-error>span::before{content:"✕ ";color:var(--bad)}.f-warning>span::before{content:"! ";color:var(--mid)}.f-info>span::before{content:"– ";color:var(--muted)}
.fix{background:var(--fix);padding:8px 12px;border-radius:8px;margin-top:6px;font-size:14px}
footer{color:var(--muted);font-size:13px;margin-top:32px}
</style>
</head>
<body>
<main>
<h1>WooCommerce agent-readiness audit</h1>
<div class="url">${esc(report.baseUrl)}</div>
<div class="score ${tone}"><span class="n">${report.score}<small>/${report.max}</small></span><span>Grade <strong>${report.grade}</strong></span><span class="url">${esc(report.auditedAt)}</span></div>
${checks}
<footer>Generated by woocommerce-agent-ready v${esc(report.toolVersion)} in ${(report.durationMs / 1000).toFixed(1)} s. Scores reflect public, unauthenticated probes only.</footer>
</main>
</body>
</html>
`;
}
